"""README is the first-clone guide (p9-final spec AC #26): required sections, and every script it names exists."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
README = (ROOT / "README.md").read_text(encoding="utf-8")
RUNBOOK = (ROOT / "docs" / "p9-final-evaluation-packaging" / "runbook.md").read_text(encoding="utf-8")

REQUIRED = ["Status", "Prerequisites", "Setup", "RunPod", "Run", "Live session", "Evaluate and release gate",
            "Benchmark", "Expected health-check output", "Teardown", "Reproducibility", "Secrets"]


def headings(text):
    return [m.group(1).strip() for m in re.finditer(r"^## (.+)$", text, re.M)]


def test_required_sections_in_order():
    found = headings(README)
    assert [h for h in found if h in REQUIRED] == REQUIRED


def test_every_named_script_exists():
    for text in (README, RUNBOOK):
        paths = set(re.findall(r"\b(?:scripts|deploy/runpod)/[\w./-]+\.(?:py|sh)\b", text))
        assert paths, "no script paths found"
        missing = sorted(p for p in paths if not (ROOT / p).is_file())
        assert missing == []


def test_every_linked_repo_file_exists():
    for base, text in ((ROOT, README), (ROOT / "docs" / "p9-final-evaluation-packaging", RUNBOOK)):
        for target in re.findall(r"\]\(([^)#\s]+)(?:#[^)]*)?\)", text):
            if target.startswith(("http://", "https://")):
                continue
            if target == "release-report.md" or target.endswith("/release-report.md"):
                continue                          # generated by scripts/release_gate.py in the live step
            assert (base / target).exists(), target


def test_secrets_table_covers_every_env_key():
    keys = re.findall(r"^([A-Z][A-Z0-9_]+)=", (ROOT / ".env.example").read_text(encoding="utf-8"), re.M)
    section = README.split("## Secrets", 1)[1].split("\n## ", 1)[0]
    missing = [k for k in keys if k not in section and not k.endswith("_TTL_DAYS")]
    assert missing == []


def test_health_check_section_lists_all_seven_checks():
    section = README.split("## Expected health-check output", 1)[1].split("\n## ", 1)[0]
    for check in ("vllm_health", "vllm_models", "vllm_chat", "postgres", "qdrant", "langfuse_health", "langfuse_trace"):
        assert check in section
    assert "7/7 checks passed" in section


def test_readme_names_no_pod_creation_command():
    assert "runpodctl" not in README and "runpodctl" not in RUNBOOK
